#!/usr/bin/env python3
"""Regenerate the built-in host shader SPIR-V header.

The Vulkan NVN replay needs a few tiny pipelines whose shaders do not come from
the game: the clear triangle used by clears a load action cannot express
(dm/gfx/glsl/clear*.{vert,frag}, the Linux counterpart of
dm/gfx/msl/clear.metal) and nvnCommandBufferDrawTexture's textured rectangle
(dm/gfx/glsl/drawtex.{vert,frag}, the counterpart of dm/gfx/msl/draw_tex.metal).
They are compiled to SPIR-V once and checked in as
src/graphics/nvn/nvn_spv_builtin.h, so building the host does not require a
GLSL compiler; this script needs the system's libshaderc only when the sources
change.

Usage: dm/gfx/tools/gen_spv_builtin.py [--check]
       --check exits non-zero when the checked-in header differs.
"""
import ctypes
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
SOURCE_DIR = os.path.join(ROOT, "dm", "gfx", "glsl")
OUT = os.path.join(ROOT, "src", "graphics", "nvn", "nvn_spv_builtin.h")

# (header name, source file, shaderc stage kind)
SHADERS = [
    ("k_clear_vs_spv", "clear.vert", 0),
    ("k_clear_fs_float_spv", "clear_float.frag", 1),
    ("k_clear_fs_uint_spv", "clear_uint.frag", 1),
    ("k_clear_fs_int_spv", "clear_int.frag", 1),
    ("k_clear_fs_empty_spv", "clear_empty.frag", 1),
    ("k_drawtex_vs_spv", "drawtex.vert", 0),
    ("k_drawtex_fs_spv", "drawtex.frag", 1),
]


def load_libshaderc():
    for name in ("libshaderc_shared.so.1", "libshaderc.so", "libshaderc.so.1"):
        try:
            return ctypes.CDLL(name)
        except OSError:
            continue
    sys.exit("[RED] libshaderc is not installed; it is only needed to regenerate the header")


def compile_spv(lib, source, kind, name):
    lib.shaderc_compiler_initialize.restype = ctypes.c_void_p
    lib.shaderc_compile_options_initialize.restype = ctypes.c_void_p
    lib.shaderc_compile_into_spv.restype = ctypes.c_void_p
    lib.shaderc_compile_into_spv.argtypes = [ctypes.c_void_p, ctypes.c_char_p, ctypes.c_size_t,
                                             ctypes.c_int, ctypes.c_char_p, ctypes.c_char_p,
                                             ctypes.c_void_p]
    lib.shaderc_result_get_bytes.restype = ctypes.c_void_p
    lib.shaderc_result_get_bytes.argtypes = [ctypes.c_void_p]
    lib.shaderc_result_get_length.restype = ctypes.c_size_t
    lib.shaderc_result_get_length.argtypes = [ctypes.c_void_p]
    lib.shaderc_result_get_compilation_status.restype = ctypes.c_int
    lib.shaderc_result_get_compilation_status.argtypes = [ctypes.c_void_p]
    lib.shaderc_result_get_error_message.restype = ctypes.c_char_p
    lib.shaderc_result_get_error_message.argtypes = [ctypes.c_void_p]
    compiler = lib.shaderc_compiler_initialize()
    options = lib.shaderc_compile_options_initialize()
    result = lib.shaderc_compile_into_spv(compiler, source, len(source), kind, name.encode(), b"main", options)
    if not result or lib.shaderc_result_get_compilation_status(result) != 0:
        msg = lib.shaderc_result_get_error_message(result) if result else b"no result"
        sys.exit("[RED] shaderc failed: " + msg.decode(errors="replace"))
    n = lib.shaderc_result_get_length(result)
    data = ctypes.string_at(lib.shaderc_result_get_bytes(result), n)
    if n % 4:
        sys.exit("[RED] shaderc returned a SPIR-V length that is not a multiple of 4")
    return data


def emit(words):
    lines = []
    for i in range(0, len(words), 8):
        lines.append("    " + ", ".join("0x%08x" % w for w in words[i:i + 8]) + ",")
    return "\n".join(lines)


def main():
    check = "--check" in sys.argv[1:]
    lib = load_libshaderc()
    out = [
        "// Generated by dm/gfx/tools/gen_spv_builtin.py from dm/gfx/glsl/clear* and drawtex.*.",
        "// Do not edit: change the GLSL and rerun the generator (--check compares this file).",
        "// Built-in host shaders: the clear triangle for clears a Vulkan load action",
        "// cannot express (per-channel colour write masks, partial stencil-bit masks,",
        "// scissor rectangles) and nvnCommandBufferDrawTexture's textured rectangle.",
        "#pragma once",
        "#include <stdint.h>",
        "",
    ]
    for name, filename, kind in SHADERS:
        path = os.path.join(SOURCE_DIR, filename)
        with open(path, "r", encoding="utf-8") as f:
            source = f.read().encode("utf-8")
        data = compile_spv(lib, source, kind, filename)
        words = [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]
        out.append("static const uint32_t %s[] = {" % name)
        out.append(emit(words))
        out.append("};")
        out.append("")
    text = "\n".join(out)
    if check:
        try:
            with open(OUT, "r", encoding="utf-8") as f:
                old = f.read()
        except OSError:
            old = None
        if old != text:
            sys.exit("[RED] %s is stale; rerun dm/gfx/tools/gen_spv_builtin.py" % OUT)
        print("built-in SPIR-V header is current")
        return
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote", OUT)


if __name__ == "__main__":
    main()
