#!/usr/bin/env python3
"""Generate the Vulkan entry stubs for the Asahi Vulkan interception layer.

Every function the guest imports must have a stable address at relocation time.
Most functions are pure forwards to the real Mesa driver; their bodies are
generated in assembly so the AArch64 calling convention is preserved exactly
(all argument and vector registers, return values, and stack arguments). The
slot for each name is filled once the real instance/device exists.

Functions that need translation (instance/device creation, the Switch VI
surface, swapchains, presentation, diagnostics) live in vk_api.c and are listed
in vk_special.txt; no stub is generated for them.
"""
import argparse
from pathlib import Path


def parse(path):
    out = []
    for line in Path(path).read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            out.append(line)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--names", required=True)
    ap.add_argument("--special", required=True)
    ap.add_argument("--out-c", required=True)
    ap.add_argument("--out-s", required=True)
    args = ap.parse_args()

    names = parse(args.names)
    special = set(parse(args.special))
    passthrough = [n for n in names if n not in special]

    c = []
    c.append('/* Generated by tools/gen_vk_entries.py; do not edit. */')
    c.append('#include <stddef.h>')
    c.append('#include <stdint.h>')
    c.append('')
    c.append('typedef struct { const char *name; void *fn; } NxVkEntry;')
    c.append('typedef struct { const char *name; void **slot; } NxVkSlot;')
    c.append('')
    for n in passthrough:
        c.append(f'void *nx_vk_slot_{n};')
    c.append('')
    c.append('const NxVkSlot nx_vk_slots[] = {')
    for n in passthrough:
        c.append(f'    {{ "{n}", &nx_vk_slot_{n} }},')
    c.append('};')
    c.append('const size_t nx_vk_slot_count = sizeof nx_vk_slots / sizeof nx_vk_slots[0];')
    c.append('')
    # The special implementations live in vk_api.c; the generated unit only
    # takes their addresses. A cross-translation-unit declaration is enough.
    for n in names:
        c.append(f'void h_{n}(void);')
    c.append('')
    c.append('const NxVkEntry nx_vk_entries[] = {')
    for n in names:
        c.append(f'    {{ "{n}", (void *)h_{n} }},')
    c.append('};')
    c.append('const size_t nx_vk_entry_count = sizeof nx_vk_entries / sizeof nx_vk_entries[0];')
    c.append('')
    Path(args.out_c).write_text("\n".join(c) + "\n", encoding="utf-8")

    s = []
    s.append('/* Generated by tools/gen_vk_entries.py; do not edit. */')
    s.append('    .text')
    for n in passthrough:
        s.append(f'    .globl h_{n}')
        s.append(f'    .type h_{n}, %function')
        s.append(f'    .hidden h_{n}')
        s.append(f'h_{n}:')
        s.append(f'    adrp x16, nx_vk_slot_{n}')
        s.append(f'    ldr x16, [x16, #:lo12:nx_vk_slot_{n}]')
        s.append('    cbz x16, 1f')
        s.append('    br x16')
        s.append('1:')
        s.append('    adrp x0, nx_vk_missing_name_' + n)
        s.append('    add x0, x0, #:lo12:nx_vk_missing_name_' + n)
        s.append('    b nx_vk_missing')
        s.append(f'    .section .rodata')
        s.append(f'    .hidden nx_vk_missing_name_{n}')
        s.append(f'nx_vk_missing_name_{n}:')
        s.append(f'    .asciz "{n}"')
        s.append('    .text')
    Path(args.out_s).write_text("\n".join(s) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
